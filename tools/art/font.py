ACUTE5 = ["...#.", "..#.."]
TILDE5 = [".##.#", "#.##."]
DIER5 = [".#.#.", "....."]

def accented(base_rows, mark, low):
    w = len(base_rows[0])
    m = [r[:w].ljust(w, ".") if len(r) >= w else r.ljust(w, ".") for r in mark]
    m = [r[(len(r) - w) // 2:][:w] if len(r) > w else r for r in mark]
    if low:
        # la marca ocupa la última fila libre de arriba y la fila 0, dejando la fila 1 vacía
        rows = list(base_rows)
        rows[0], rows[1] = m[1].ljust(w, ".")[:w], "." * w
        return rows, ["." * w, m[0].ljust(w, ".")[:w]]
    return list(base_rows), [r.ljust(w, ".")[:w] for r in m]

def build():
    glyphs = {}
    for d in (UP, LOW, DIG, PUN):
        for k, v in d.items():
            glyphs[k] = (g(*v), None)
    for base, ch in (("a", "á"), ("e", "é"), ("o", "ó"), ("u", "ú")):
        glyphs[ch] = accented(g(*LOW[base]), ACUTE5, True)
    glyphs["í"] = (g("#.", "..", "#.", "#.", "#.", "#.", "#."), [".", ".#"])
    glyphs["ñ"] = accented(g(*LOW["n"]), TILDE5, True)
    glyphs["ü"] = (accented(g(*LOW["u"]), [".....", ".#.#."], True)[0], None)
    for base, ch in (("A", "Á"), ("E", "É"), ("O", "Ó"), ("U", "Ú")):
        glyphs[ch] = (g(*UP[base]), ACUTE5)
    glyphs["Í"] = (g(*UP["I"]), [".#", "#."])
    glyphs["Ñ"] = (g(*UP["N"]), TILDE5)
    glyphs["Ü"] = (g(*UP["U"]), DIER5)
    chars = list(glyphs)
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    atlas = Image.new("RGBA", (cols * 8, rows * 12), (0, 0, 0, 0))
    meta = {"cell": [8, 12], "cols": cols, "height": 11, "baseline": 8, "glyphs": {}}
    for i, ch in enumerate(chars):
        rows9, top = glyphs[ch]
        w = max(len(r) for r in rows9)
        ox, oy = (i % cols) * 8, (i // cols) * 12
        if top:
            for y, r in enumerate(top):
                for x, c in enumerate(r):
                    if c == "#": atlas.putpixel((ox + x, oy + y), (255, 255, 255, 255))
        for y, r in enumerate(rows9):
            for x, c in enumerate(r):
                if c == "#": atlas.putpixel((ox + x, oy + 2 + y), (255, 255, 255, 255))
        meta["glyphs"][ch] = [i, w]
    out = ROOT / "assets/atlas"; out.mkdir(parents=True, exist_ok=True)
    atlas.save(out / "font.png")
    json.dump(meta, open(out / "font.json", "w", encoding="utf-8"), ensure_ascii=False)
    print("OK", len(chars), "glifos")

if __name__ == "__main__":
    build()
